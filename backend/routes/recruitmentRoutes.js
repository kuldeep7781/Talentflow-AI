import { Router } from "express";
import * as controller from "../controllers/recruitmentController.js";
import { authenticate, allowRoles } from "../middleware/authMiddleware.js";
import { resumeUpload } from "../middleware/uploadMiddleware.js";
const router = Router();
router.get("/jobs", controller.getJobs);
router.post("/jobs", authenticate, allowRoles("HR"), controller.createJob);
router.patch("/jobs/:id", authenticate, allowRoles("HR"), controller.updateJob);
router.delete("/jobs/:id", authenticate, allowRoles("HR"), controller.deleteJob);
router.post("/jobs/:jobId/apply", authenticate, allowRoles("CANDIDATE"), resumeUpload.single("resume"), controller.apply);
router.get("/applications/mine", authenticate, allowRoles("CANDIDATE"), controller.myApplications);
router.get("/applications", authenticate, allowRoles("HR"), controller.applications);
router.get("/applications/:id/resume", authenticate, allowRoles("HR", "INTERVIEWER"), controller.downloadApplicationResume);
router.patch("/applications/:id/status", authenticate, allowRoles("HR"), controller.updateApplicationStatus);
router.get("/interviewers", authenticate, allowRoles("HR"), controller.interviewers);
router.get("/interviews", authenticate, allowRoles("HR", "INTERVIEWER"), controller.interviews);
router.post("/interviews", authenticate, allowRoles("HR"), controller.scheduleInterview);
router.post("/interviews/:id/feedback", authenticate, allowRoles("INTERVIEWER"), controller.feedback);
router.get("/dashboard/stats", authenticate, allowRoles("HR"), controller.dashboard);
export default router;
